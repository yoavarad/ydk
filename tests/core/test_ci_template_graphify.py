def _loop_guard_patterns(root: Path) -> list[re.Pattern[str]]:
    _, parsed = _gitlab(root / "gl-render")
    cond = parsed["ydk-graphify-update"]["rules"][0]["if"]
    return [re.compile(p) for p in re.findall(r"\$CI_COMMIT_TITLE !~ /((?:\\.|[^/\\])*)/", cond)]


@pytest.mark.parametrize(
    ("title", "excluded"),
    [
        ("chore(graphify): update graph", True),
        ("Merge branch 'chore/graphify-update' into 'main'", True),
        ("feat(ci): add graphify", False),
        ("fix: merge branch handling", False),
    ],
)
def test_gitlab_loop_guard_titles(tmp_path: Path, title: str, excluded: bool) -> None:
    patterns = _loop_guard_patterns(tmp_path)
    assert len(patterns) == 2
    assert any(p.search(title) for p in patterns) is excluded


