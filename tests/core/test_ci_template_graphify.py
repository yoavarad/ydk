def _config(root: Path, stack: str, remote: str = "github", extra: str = "") -> None:
    (root / ".ydk").mkdir(parents=True, exist_ok=True)
    (root / ".ydk" / "config.yaml").write_text(
        f"project:\n  name: demo\n  remote: {remote}\n  stack: {stack}\n{extra}", encoding="utf-8"
    )


def _rendered(root: Path, stack: str = "python-cli") -> tuple[str, dict[Any, Any]]:
    _config(root, stack)
    generate_ci(root, force=False, version="1.5.0")
    text = (root / ".github" / "workflows" / OUTPUT).read_text(encoding="utf-8")
    return text, yaml.safe_load(text)


def _run_text(data: dict[Any, Any]) -> str:
    return "\n".join(s["run"] for s in data["jobs"]["graphify"]["steps"] if "run" in s)


