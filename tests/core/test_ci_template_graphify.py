# --- Behavior: run the generated shell blocks in a temp git repo with boundary stubs (graphify, gh, pip) ---

SH = shutil.which("sh")
needs_sh = pytest.mark.skipif(
    SH is None,
    reason="POSIX sh not found on PATH (on Windows install Git for Windows); behavior tests need it",
)

GRAPHIFY_STUB = """#!/bin/sh
mkdir -p graphify-out/cache graphify-out/2026-01-01
echo "$$" > graphify-out/cache/stat-index.json
echo noise > graphify-out/2026-01-01/scratch.txt
if [ -n "$STUB_GRAPH_CHANGE" ]; then echo "$STUB_GRAPH_CHANGE" >> graphify-out/graph.json; fi
if [ -n "$STUB_ODD_FILE" ]; then echo x > "graphify-out/café notes.json"; fi
"""
GH_STUB = """#!/bin/sh
echo "$*" >> "$GH_LOG"
if [ "$1 $2" = "pr list" ]; then echo "$GH_OPEN_PR"; fi
if [ "$1 $2" = "pr create" ]; then echo https://example.test/pr/1; fi
"""
PIP_STUB = "#!/bin/sh\nexit 0\n"
CURL_STUB = '#!/bin/sh\necho "${CURL_OPEN_MR:-[]}"\n'
PRE_RECEIVE = r"""#!/bin/sh
[ -z "$PUSH_OPT_LOG" ] || {
  echo "push" >> "$PUSH_OPT_LOG"
  i=0
  while [ "$i" -lt "${GIT_PUSH_OPTION_COUNT:-0}" ]; do
    eval "echo \"\$GIT_PUSH_OPTION_$i\"" >> "$PUSH_OPT_LOG"
    i=$((i + 1))
  done
}
exit 0
"""


def _git(cwd: Path, *args: str) -> str:
    out = subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", *args],
        cwd=cwd,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    return out.stdout.strip()


def _write_exec(path: Path, body: str) -> None:
    path.write_text(body, encoding="utf-8", newline="\n")
    path.chmod(0o755)


class Sandbox:
    """A work clone plus bare origin, with stub `graphify`/`gh`/`pip` on PATH."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.origin = root / "origin.git"
        self.work = root / "work"
        self.bin = root / "bin"
        self.gh_log = root / "gh.log"
        self.opt_log = root / "opt.log"
        subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(self.origin)], check=True)
        _git(self.origin, "config", "receive.advertisePushOptions", "true")
        _write_exec(self.origin / "hooks" / "pre-receive", PRE_RECEIVE)
        self.work.mkdir(parents=True)
        _git(self.work, "init", "-q", "-b", "main")
        (self.work / "graphify-out").mkdir()
        (self.work / "graphify-out" / "graph.json").write_text("base\n", encoding="utf-8", newline="\n")
        (self.work / ".gitignore").write_text("graphify-out/cache/\n", encoding="utf-8", newline="\n")
        _git(self.work, "add", "-A")
        _git(self.work, "commit", "-qm", "init")
        _git(self.work, "remote", "add", "origin", str(self.origin))
        _git(self.work, "push", "-q", "origin", "main")
        self.bin.mkdir()
        for name, body in (("graphify", GRAPHIFY_STUB), ("gh", GH_STUB), ("pip", PIP_STUB), ("curl", CURL_STUB)):
            _write_exec(self.bin / name, body)
        self.gh_log.write_text("", encoding="utf-8")
        self.opt_log.write_text("", encoding="utf-8")

    def run(
        self, script: str, *, change: str = "", open_pr: str = "", open_mr: str = "[]", odd_file: bool = False
    ) -> None:
        _git(self.work, "checkout", "-q", "main")
        env = {
            **os.environ,
            "PATH": f"{self.bin}{os.pathsep}{os.environ['PATH']}",
            "GH_LOG": str(self.gh_log),
            "PUSH_OPT_LOG": str(self.opt_log),
            "GH_OPEN_PR": open_pr,
            "STUB_GRAPH_CHANGE": change,
            "GRAPHIFY_BRANCH": BRANCH,
            "DEFAULT_BRANCH": "main",
            "RUNNER_TEMP": str(self.root),
            "CI_DEFAULT_BRANCH": "main",
            "CI_SERVER_HOST": "gitlab.example.test",
            "GRAPHIFY_BOT_TOKEN": "tok",
            "CI_API_V4_URL": "https://gitlab.example.test/api/v4",
            "CI_PROJECT_ID": "1",
            "CURL_OPEN_MR": open_mr,
            "STUB_ODD_FILE": "1" if odd_file else "",
        }
        assert SH is not None
        done = subprocess.run([SH, "-e", "-c", script], cwd=self.work, env=env, capture_output=True, text=True)
        assert done.returncode == 0, done.stderr

    def remote_commits(self) -> list[str]:
        out = subprocess.run(
            ["git", "log", "--format=%s", f"main..{BRANCH}"], cwd=self.origin, capture_output=True, text=True
        )
        return out.stdout.splitlines() if out.returncode == 0 else []

    def branch_files(self) -> list[str]:
        return _git(self.origin, "-c", "core.quotePath=off", "diff", "--name-only", f"main..{BRANCH}").splitlines()

    def pr_creates(self) -> int:
        return sum(1 for line in self.gh_log.read_text(encoding="utf-8").splitlines() if line.startswith("pr create"))

    def pushes(self) -> list[list[str]]:
        """Push options received per push, in order."""
        groups: list[list[str]] = []
        for line in self.opt_log.read_text(encoding="utf-8").splitlines():
            if line == "push":
                groups.append([])
            else:
                groups[-1].append(line)
        return groups


def _github_script(root: Path) -> str:
    _, data = _rendered(root / "gh-render")
    step = next(s["run"] for s in data["jobs"]["graphify"]["steps"] if s.get("name") == "Open graph update PR")
    return "graphify update .\n" + step


def _gitlab_script(root: Path) -> str:
    _, parsed = _gitlab(root / "gl-render")
    return "\n".join(parsed["ydk-graphify-update"]["script"])


