"""Tests for the CI workflow generator engine."""

from __future__ import annotations

from typing import TYPE_CHECKING

import pytest
import yaml

from ydk.core import ci_generator
from ydk.core.ci_generator import (
    PR_TEMPLATE,
    CiConfigError,
    CiContext,
    CiTarget,
    generate_ci,
    is_release_version,
    render,
    select_stack_target,
)

if TYPE_CHECKING:
    from pathlib import Path


def _write_config(root: Path, remote: str = "github", stack: str = "python-cli") -> None:
    (root / ".ydk").mkdir(parents=True, exist_ok=True)
    (root / ".ydk" / "config.yaml").write_text(
        f"project:\n  name: demo\n  remote: {remote}\n  stack: {stack}\n  spec_location: docs/specs\n"
        "components:\n  components_path: .ydk/components\n  schemas_path: .ydk/schemas\n",
        encoding="utf-8",
    )


def _templates(tmp_path: Path) -> Path:
    tdir = tmp_path / "tpl"
    tdir.mkdir()
    (tdir / "demo.yml").write_text(
        "name: demo\n# ydk {{YDK_VERSION}} stack={{STACK}} spec={{SPEC_LOCATION}}\n"
        "# comp={{COMPONENTS_PATH}} schemas={{SCHEMAS_PATH}}\n"
        "group: ${{ github.workflow }}\n",
        encoding="utf-8",
    )
    return tdir


DEMO = CiTarget(template="demo.yml", output="demo.yml", purpose="Demo workflow")
NEVER = CiTarget(template="demo.yml", output="never.yml", purpose="Never", condition=lambda ctx: False)


def _ctx(version: str = "1.5.0") -> CiContext:
    return CiContext(
        version=version,
        stack="python-cli",
        spec_location="docs/specs",
        components_path=".ydk/components",
        schemas_path=".ydk/schemas",
    )


def test_registry_lists_pr_checks() -> None:
    assert "ydk-pr-checks.yml" in [t.output for t in ci_generator.CI_TARGETS]


def test_templates_dir_is_package_data() -> None:
    assert ci_generator.TEMPLATES_DIR.is_dir()


def test_render_header_and_placeholders() -> None:
    out = render("x: {{YDK_VERSION}}\ns: {{STACK}}\ng: ${{ github.ref }}\n", _ctx())
    assert out.startswith("# Generated by ydk ci init v1.5.0. Re-run 'ydk ci init --force' to regenerate.\n")
    assert "x: 1.5.0" in out
    assert "s: python-cli" in out
    assert "g: ${{ github.ref }}" in out


def test_render_is_deterministic() -> None:
    assert render("a {{YDK_VERSION}}", _ctx()) == render("a {{YDK_VERSION}}", _ctx())


