def test_fresh_writes_targets_and_pr_template(tmp_path: Path) -> None:
    _write_config(tmp_path)
    result = generate_ci(
        tmp_path, force=False, version="1.5.0", targets=[DEMO, NEVER], templates_dir=_templates(tmp_path)
    )
    wf = tmp_path / ".github" / "workflows" / "demo.yml"
    assert wf.read_text(encoding="utf-8").startswith("# Generated by ydk ci init v1.5.0.")
    body = wf.read_text(encoding="utf-8")
    assert "stack=python-cli spec=docs/specs" in body
    assert "comp=.ydk/components schemas=.ydk/schemas" in body
    assert not (tmp_path / ".github" / "workflows" / "never.yml").exists()
    pr = tmp_path / ".github" / "PULL_REQUEST_TEMPLATE.md"
    assert pr.read_text(encoding="utf-8") == PR_TEMPLATE
    assert [(f.path, f.action) for f in result.files] == [
        (".github/workflows/demo.yml", "written"),
        (".github/PULL_REQUEST_TEMPLATE.md", "written"),
    ]
    assert result.files[0].purpose == "Demo workflow"
    assert result.written == [".github/workflows/demo.yml", ".github/PULL_REQUEST_TEMPLATE.md"]
    assert result.skipped == []
    assert result.unpublished is False


def test_second_run_skips_and_leaves_files_untouched(tmp_path: Path) -> None:
    _write_config(tmp_path)
    tdir = _templates(tmp_path)
    generate_ci(tmp_path, force=False, version="1.5.0", targets=[DEMO], templates_dir=tdir)
    wf = tmp_path / ".github" / "workflows" / "demo.yml"
    pr = tmp_path / ".github" / "PULL_REQUEST_TEMPLATE.md"
    wf.write_text("custom", encoding="utf-8")
    before = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in (wf, pr)}
    result = generate_ci(tmp_path, force=False, version="1.6.0", targets=[DEMO], templates_dir=tdir)
    assert {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in (wf, pr)} == before
    assert [f.action for f in result.files] == ["skipped (exists)", "skipped (exists)"]
    assert result.written == []
    assert result.skipped == [".github/workflows/demo.yml", ".github/PULL_REQUEST_TEMPLATE.md"]


def test_force_overwrites_targets_only(tmp_path: Path) -> None:
    _write_config(tmp_path)
    tdir = _templates(tmp_path)
    generate_ci(tmp_path, force=False, version="1.5.0", targets=[DEMO], templates_dir=tdir)
    wf = tmp_path / ".github" / "workflows" / "demo.yml"
    pr = tmp_path / ".github" / "PULL_REQUEST_TEMPLATE.md"
    other = tmp_path / ".github" / "workflows" / "mine.yml"
    other.write_text("mine", encoding="utf-8")
    wf.write_text("custom", encoding="utf-8")
    pr.write_text("custom pr", encoding="utf-8")
    other_mtime = other.stat().st_mtime_ns
    result = generate_ci(tmp_path, force=True, version="1.6.0", targets=[DEMO], templates_dir=tdir)
    assert wf.read_text(encoding="utf-8").startswith("# Generated by ydk ci init v1.6.0.")
    assert pr.read_text(encoding="utf-8") == PR_TEMPLATE
    assert other.read_text(encoding="utf-8") == "mine"
    assert other.stat().st_mtime_ns == other_mtime
    assert [f.action for f in result.files] == ["overwritten", "overwritten"]
    assert result.written == [".github/workflows/demo.yml", ".github/PULL_REQUEST_TEMPLATE.md"]


PYTHON_STACKS = ["python-fastapi", "python-cli"]


def _load_workflow(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


