def test_existing_ci_yml_skipped_then_forced(tmp_path: Path) -> None:
    _write_config(tmp_path, stack="python-fastapi")
    (tmp_path / "uv.lock").write_text("", encoding="utf-8")
    ci = tmp_path / ".github" / "workflows" / "ci.yml"
    ci.parent.mkdir(parents=True)
    ci.write_text("hand-written", encoding="utf-8")
    result = generate_ci(tmp_path, force=False, version="1.5.0")
    assert ci.read_text(encoding="utf-8") == "hand-written"
    assert ".github/workflows/ci.yml" in result.skipped
    forced = generate_ci(tmp_path, force=True, version="1.5.0")
    assert ci.read_text(encoding="utf-8").startswith("# Generated by ydk ci init v1.5.0.")
    assert ".github/workflows/ci.yml" in forced.written
    assert next(f for f in forced.files if f.path == ".github/workflows/ci.yml").action == "overwritten"


def test_version_defaults_to_installed_metadata(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _write_config(tmp_path)
    monkeypatch.setattr(ci_generator.importlib.metadata, "version", lambda name: "1.5.0.dev3")
    result = generate_ci(tmp_path, force=False, targets=[DEMO], templates_dir=_templates(tmp_path))
    assert result.version == "1.5.0.dev3"
    assert result.unpublished is True
    text = (tmp_path / ".github" / "workflows" / "demo.yml").read_text(encoding="utf-8")
    assert "# ydk 1.5.0.dev3" in text
