@pytest.mark.parametrize("stack", PYTHON_STACKS)
def test_python_stack_writes_ci_yml(tmp_path: Path, stack: str) -> None:
    _write_config(tmp_path, stack=stack)
    (tmp_path / "uv.lock").write_text("", encoding="utf-8")
    result = generate_ci(tmp_path, force=False, version="1.5.0")
    ci = tmp_path / ".github" / "workflows" / "ci.yml"
    text = ci.read_text(encoding="utf-8")
    assert text.startswith("# Generated by ydk ci init v1.5.0.")
    assert "ydk" not in text.split("\n", 1)[1]  # nothing YDK-specific below the header
    wf = _load_workflow(ci)
    triggers = wf[True]  # YAML 1.1 parses the `on` key as boolean True
    assert "pull_request" in triggers
    assert "workflow_dispatch" in triggers
    assert triggers["push"]["branches"] == ["main"]
    assert wf["permissions"] == {"contents": "read"}
    assert wf["concurrency"] == {
        "group": "${{ github.workflow }}-${{ github.ref }}",
        "cancel-in-progress": "${{ github.event_name == 'pull_request' }}",
    }
    assert set(wf["jobs"]) == {"lint", "test"}
    for job in wf["jobs"].values():
        steps = job["steps"]
        assert steps[0]["uses"] == "actions/checkout@v4"
        assert steps[1] == {
            "uses": "astral-sh/setup-uv@v7",
            "with": {"enable-cache": True, "python-version": "3.13"},
        }
        assert steps[2]["run"] == "uv sync --locked --all-extras --dev"
    lint_runs = [s["run"] for s in wf["jobs"]["lint"]["steps"][3:]]
    assert lint_runs == ["uv run ruff check .", "uv run ruff format --check .", "uv run ty check"]
    test_runs = [s["run"] for s in wf["jobs"]["test"]["steps"][3:]]
    assert test_runs == ["uv run pytest -q --tb=short"]
    ci_row = next(f for f in result.files if f.path == ".github/workflows/ci.yml")
    assert (ci_row.action, ci_row.purpose) == ("written", "stack CI (python)")
    assert result.warnings == []


def _setup_uv_versions(root: Path) -> list[str]:
    wf = _load_workflow(root / ".github" / "workflows" / "ci.yml")
    return [
        step["with"]["python-version"]
        for job in wf["jobs"].values()
        for step in job["steps"]
        if step.get("uses", "").startswith("astral-sh/setup-uv")
    ]


